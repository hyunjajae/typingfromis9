/* =========================================================================
   기능 공개 스위치
   =========================================================================

   릴스를 순서대로 올리면서 기능을 하나씩 공개하기 위한 파일입니다.
   ★ 코드는 전부 그대로 있고, 여기서 화면에 보일지만 정합니다.

   공개하고 싶어지면 그 줄을 false → true 로 바꾸고 저장한 뒤
   git push 하면 몇 분 뒤 사이트에 반영됩니다.

   -------------------------------------------------------------------------
   릴스 계획

     1편  타이핑 게임          →  지금 상태 (둘 다 false)
     2편  노래 기다려주기      →  autoWait 를 true 로
     3편  인트로 퀴즈          →  quiz 를 true 로

   ========================================================================= */

const FEATURES = {

  // ── 노래 맞춰주기 (기다려주기) ─────────────────────────────
  // 타자가 느리면 노래가 멈춰서 기다려주는 기능.
  // false 면 : 오디오 바의 "노래 맞춰주기" 버튼이 사라지고,
  //            노래가 기다려주지 않고 계속 흘러갑니다.
  autoWait: true,

  // ── 인트로 퀴즈 ───────────────────────────────────────────
  // false 면 : 시작 화면에서 "02 인트로 퀴즈" 카드가 사라지고,
  //            랭킹 화면도 가사 타이핑만 보여줍니다.
  quiz: true,

  // ── 응원법 (구간 도전) ────────────────────────────────────
  // false 면 : 시작 화면에서 "03 응원법" 카드가 사라집니다.
  //            (곡에 chants 가 하나도 없으면 자동으로도 숨겨집니다)
  chant: true,

  // 응원법 카드에 붙는 "NEW" 배지.
  // 좀 지나서 새 기능 느낌이 없어지면 false 로 바꾸세요.
  chantIsNew: true,

  // ── 응원법 음성 모드 ──────────────────────────────────────
  // 마이크에 대고 실제로 외치는 방식.
  // false 면 : 입력 방식 선택 화면 없이 바로 타이핑으로 들어갑니다.
  chantVoice: true,

  // ── 싱크 조정 (나 전용) ───────────────────────────────────
  // 가사·응원법 시각을 이 사이트 안에서 직접 다듬는 화면입니다.
  // true 면 시작 화면 맨 아래에 링크가 생깁니다.
  // false 여도 주소 뒤에 #tune 을 붙이면 열 수 있습니다.
  //   예) http://localhost:5660/#tune
  devTune: true

};
